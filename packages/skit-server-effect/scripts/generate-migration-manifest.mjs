import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDirectory = join(packageRoot, "migrations");
const outputPath = join(packageRoot, "src", "readiness", "migrations.generated.ts");
const migrationName = /^(\d{4})_[a-z0-9_]+\.sql$/;

export const migrationManifestSource = (entries) => {
  const migrations = entries.filter((entry) => entry.endsWith(".sql")).sort();
  const ids = new Set();
  for (const name of migrations) {
    const match = migrationName.exec(name);
    if (!match) throw new Error(`invalid migration filename: ${name}`);
    if (ids.has(match[1])) throw new Error(`duplicate migration id: ${match[1]}`);
    ids.add(match[1]);
  }
  if (migrations.length === 0) throw new Error("no D1 migrations found");

  const rows = migrations.map((name) => `  ${JSON.stringify(name)},`).join("\n");
  return `// Generated by scripts/generate-migration-manifest.mjs from migrations/*.sql.\n// Do not edit this file by hand.\nexport const expectedMigrations = [\n${rows}\n] as const;\n`;
};

export const main = async (args = process.argv.slice(2)) => {
  const source = migrationManifestSource(await readdir(migrationsDirectory));
  if (args.includes("--check")) {
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== source)
      throw new Error("migration manifest is stale; run pnpm generate:migrations");
    return;
  }
  await writeFile(outputPath, source);
};

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    await main();
  } catch (cause) {
    console.error(cause instanceof Error ? cause.message : cause);
    process.exitCode = 1;
  }
}
